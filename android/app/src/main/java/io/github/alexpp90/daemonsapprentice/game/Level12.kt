package io.github.alexpp90.daemonsapprentice.game

/** Level 12, "How Apps Talk": system services, Binder, a raw call, and a question refused inside the system. */
object Level12 {

    private val at: suspend TaskContext.() -> Unit = { goTo(dirs.playground) }

    val level = Level(
        number = 12,
        title = "How Apps Talk",
        intro = listOf(
            "${Pid1.RUNNING}  Your app cannot see other processes, cannot read their files. And yet it can show a notification, ask for your location, play a sound. How?",
            "It asks the system. Android's **system services** do the work, and apps call them through **Binder**: a messenger built into the kernel. Today you make such calls yourself.",
        ),
        tasks = listOf(
            Task(
                id = "t12_1", title = "The services",
                chunks = listOf("`service list` names them. The first few:\n\n      `service list | head`"),
                command = "service list | head", chips = listOf("service", "list", "|", "head"), keys = listOf("|"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("service") && a.outHas("services") },
                hint1 = "`service list`, a pipe, `head`.", hint2 = "`service list | head`",
                solution = "service list | head", solutionWhy = "Each line: a service's name and, in brackets, the language it speaks (its interface).",
                fact = "`activity` runs apps, `package` knows what is installed, `location` knows where you are.",
                how = "service printed its list",
            ),
            Task(
                id = "t12_2", title = "How many?",
                chunks = listOf("      `service list | wc -l`"),
                command = "service list | wc -l", chips = listOf("service", "list", "|", "wc", "-l"), keys = listOf("|", "-"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("wc") && (a.output.trim().toIntOrNull() ?: 0) > 20 },
                hint1 = "`service list` into `wc -l`.", hint2 = "`service list | wc -l`",
                solution = "service list | wc -l", solutionWhy = "Hundreds of services, in a handful of system processes.",
                fact = "Android 10 had about 160; newer phones have over 300. Every new feature brings a service.",
                how = "wc counted the services",
            ),
            Task(
                id = "t12_3", title = "Is it there?",
                chunks = listOf("Ask for one by name:\n\n      `service check activity`"),
                command = "service check activity", chips = listOf("service", "check", "activity"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("service") && a.outHas("found") },
                hint1 = "`service check` and the name `activity`.", hint2 = "`service check activity`",
                solution = "service check activity", solutionWhy = "found: the activity manager, which starts apps and decides who is in front.",
                fact = "Your app talked to it when it started, and again every time you switched apps.",
                how = "service check found it",
            ),
            Task(
                id = "t12_4", title = "Listening threads",
                card = "Calls go both ways: the system also calls your app (\"you are in front now\", \"you are in the background\"). Your app keeps a few **Binder threads** waiting for them.",
                chunks = listOf("Count them:\n\n      `cat /proc/\$PPID/task/*/comm | grep -c -i binder`"),
                command = "cat /proc/\$PPID/task/*/comm | grep -c -i binder",
                chips = listOf("cat", "/proc/\$PPID/task/*/comm", "|", "grep", "-c", "-i", "binder"), keys = listOf("/", "$", "*", "|", "-"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("grep") && (a.output.trim().toIntOrNull() ?: 0) > 0 },
                hint1 = "The threads from Level 11, then `grep -c -i binder`.", hint2 = "`cat /proc/\$PPID/task/*/comm | grep -c -i binder`",
                solution = "cat /proc/\$PPID/task/*/comm | grep -c -i binder", solutionWhy = "`-c` counts, `-i` ignores capitals: a few threads, waiting.",
                fact = "If the system's call finds them all busy, it waits. That is one way an app gets the \"isn't responding\" dialog.",
                how = "grep counted binder threads",
            ),
            Task(
                id = "t12_5", title = "A raw call",
                card = "`service call` sends a call by hand: a service and a number. 1598968902 is a special number every service understands: \"what is your interface called?\"",
                chunks = listOf("      `service call activity 1598968902`"),
                command = "service call activity 1598968902", chips = listOf("service", "call", "activity", "1598968902"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("service") && a.outHas("Parcel") },
                hint1 = "`service call`, the service, the long number.", hint2 = "`service call activity 1598968902`",
                solution = "service call activity 1598968902", solutionWhy = "The answer, a Parcel, spells on the right `a.n.d.r.o.i.d...I.A.c.t.i.v.i.t.y.M.a.n.a.g.e.r`.",
                fact = "android.app.IActivityManager, two bytes per letter. The number is the letters `_NTF` read as one number: the interface transaction.",
                how = "the answer is a Parcel",
            ),
            Task(
                id = "t12_6", title = "A question refused",
                chunks = listOf("Ask the settings service for the screen brightness. **A refusal is the right result.**\n\n      `settings get system screen_brightness`"),
                command = "settings get system screen_brightness", chips = listOf("settings", "get", "system", "screen_brightness"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("settings") && (a.outHas("SecurityException") || a.outHas("Permission Denial")) },
                hint1 = "`settings get`, then `system`, then the setting's name.", hint2 = "`settings get system screen_brightness`",
                solution = "settings get system screen_brightness", solutionWhy = "A SecurityException, with a stack trace from inside the system.",
                fact = "Read the stack trace from the bottom: `Binder.execTransact` received your call, the settings service ran, and its permission check said no. The question reached the system; the answer was a refusal. (The game hands these commands a pipe instead of its terminal: the system will not touch an app's terminal.)",
                how = "the output shows the SecurityException",
            ),
            Task(
                id = "t12_7", title = "Hidden services",
                chunks = listOf("`dumpsys` asks a service to describe itself. The battery:\n\n      `dumpsys battery`"),
                command = "dumpsys battery", chips = listOf("dumpsys", "battery"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("dumpsys") && a.outHas("battery") },
                hint1 = "`dumpsys` and `battery`.", hint2 = "`dumpsys battery`",
                solution = "dumpsys battery", solutionWhy = "Can't find service: for an app it does not even exist.",
                fact = "Some services are hidden from apps altogether. Your app can ask the battery level through a public way that cannot be misused, not this one.",
                how = "dumpsys answered about battery",
            ),
            Task(
                id = "t12_8", title = "The line to the kernel",
                chunks = listOf("Your app's open files include its line to Binder:\n\n      `ls -l /proc/\$PPID/fd | grep binder`"),
                command = "ls -l /proc/\$PPID/fd | grep binder",
                chips = listOf("ls", "-l", "/proc/\$PPID/fd", "|", "grep", "binder"), keys = listOf("-", "/", "$", "|"),
                drive = "device",
                prep = at,
                check = { a, _ -> a.ran("grep") && a.outHas("binder") },
                hint1 = "`ls -l` the fd folder, then `grep binder`.", hint2 = "`ls -l /proc/\$PPID/fd | grep binder`",
                solution = "ls -l /proc/\$PPID/fd | grep binder", solutionWhy = "`/dev/binder`: every call your app makes goes through this one open file.",
                fact = "`fd` lists the files a process has open, by number. Binder is a device, like the ones in /dev from Level 5: one of the few an app may use.",
                how = "the app has /dev/binder open",
            ),
        ),
        outro = listOf(
            "System services do the work; Binder carries the calls; the services check who is asking.",
            "Next: your app itself. It is a file, and you can take it apart.",
        ),
        explore = listOf(
            "Settings > Apps > (an app) > Permissions: each permission is a check a system service makes when the app calls it.",
        ),
    )
}
