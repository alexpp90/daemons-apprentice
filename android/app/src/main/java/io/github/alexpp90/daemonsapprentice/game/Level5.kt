package io.github.alexpp90.daemonsapprentice.game

import java.io.File

/** Level 5, "Your Phone Is a Linux Computer": the machine under the apps, and its first wall. */
object Level5 {

    private val at: suspend TaskContext.() -> Unit = {
        File(dirs.playground, "timeline.txt").ensureText(Level0.timeline)
        File(dirs.playground, "nothing.txt").delete()
        goTo(dirs.playground)
    }

    val level = Level(
        number = 5,
        title = "Your Phone Is a Linux Computer",
        intro = listOf(
            "${Pid1.INSPECTING}  You have been talking to me for four levels. Time you learned what I live in.",
            "Under the apps, the icons and the home screen, your phone runs **Linux**: the same system as most servers, the cloud and many laptops. Today you ask the phone about itself.",
        ),
        tasks = listOf(
            Task(
                id = "t5_1", title = "Which system?",
                chunks = listOf("`uname` names the system's core, the **kernel**:\n\n      `uname`"),
                command = "uname", chips = listOf("uname"),
                prep = at,
                check = { a, _ -> a.ran("uname") && a.output.trim() == "Linux" },
                hint1 = "Just the command, nothing after it.", hint2 = "`uname`",
                solution = "uname", solutionWhy = "`uname` prints the kernel's name: Linux.",
                fact = "The kernel is the part that talks to the hardware: memory, the processor, the radio. Android is built on top of it.",
                how = "uname printed Linux",
            ),
            Task(
                id = "t5_2", title = "Which Linux?",
                chunks = listOf("`-r` asks for its release, the version:\n\n      `uname -r`"),
                command = "uname -r", chips = listOf("uname", "-r"), keys = listOf("-"),
                prep = at,
                check = { a, _ -> a.ran("uname") && "-r" in a.words && Regex("""^\d+\.\d+""").containsMatchIn(a.output.trim()) },
                hint1 = "`uname`, a space, `-r`.", hint2 = "`uname -r`",
                solution = "uname -r", solutionWhy = "`-r` asks uname for the kernel's version number.",
                fact = "On newer phones the version has `android` in it: Linux, built for Android by Google and the phone's maker.",
                how = "uname -r printed a version number",
            ),
            Task(
                id = "t5_3", title = "Which Android?",
                card = "Android keeps its own settings in **properties**: names with dots in them. `getprop` reads one. It is an Android command; a computer does not have it.",
                chunks = listOf("Ask for the Android version:\n\n      `getprop ro.build.version.release`"),
                command = "getprop ro.build.version.release", chips = listOf("getprop", "ro.build.version.release"),
                prep = at,
                check = { a, _ -> a.ran("getprop") && Regex("""^\d+""").containsMatchIn(a.output.trim()) },
                hint1 = "`getprop` and the property's long name, with its dots.", hint2 = "`getprop ro.build.version.release`",
                solution = "getprop ro.build.version.release", solutionWhy = "`getprop` reads the property that holds the Android version.",
                fact = "`ro` means read-only: set when the phone was built. Settings > About phone shows the same number.",
                how = "getprop printed a version number",
            ),
            Task(
                id = "t5_4", title = "Which phone?",
                chunks = listOf("And the model:\n\n      `getprop ro.product.model`"),
                command = "getprop ro.product.model", chips = listOf("getprop", "ro.product.model"),
                prep = at,
                check = { a, _ -> a.ran("getprop") && "ro.product.model" in a.words && a.output.isNotBlank() },
                hint1 = "`getprop` again, with `ro.product.model`.", hint2 = "`getprop ro.product.model`",
                solution = "getprop ro.product.model", solutionWhy = "The model property names this phone.",
                fact = "`getprop` alone lists every property, hundreds of them. Apps read some of them to know what phone they run on.",
                how = "getprop ro.product.model printed something",
            ),
            Task(
                id = "t5_5", title = "How many brains?",
                chunks = listOf("A processor has several **cores**, each working on its own. Count them:\n\n      `nproc`"),
                command = "nproc", chips = listOf("nproc"),
                prep = at,
                check = { a, _ -> a.ran("nproc") && a.output.trim().toIntOrNull()?.let { it > 0 } == true },
                hint1 = "One word: n-proc.", hint2 = "`nproc`",
                solution = "nproc", solutionWhy = "`nproc` counts the processor cores this app may use.",
                fact = "Most phones have eight cores: some big and fast, some small and frugal. Linux moves work between them to save battery.",
                how = "nproc printed a number",
            ),
            Task(
                id = "t5_6", title = "How much memory?",
                chunks = listOf("`free` shows the memory; `-h` makes the numbers human (G for gigabytes):\n\n      `free -h`"),
                command = "free -h", chips = listOf("free", "-h"), keys = listOf("-"),
                prep = at,
                check = { a, _ -> a.ran("free") && a.outHas("Mem") },
                hint1 = "`free`, a space, `-h`.", hint2 = "`free -h`",
                solution = "free -h", solutionWhy = "`free -h` shows total, used and free memory in readable units.",
                fact = "Almost no memory is free? That is on purpose: Android keeps apps you left in memory, so they open fast. It throws them out when space is needed (Level 15).",
                how = "free printed its Mem line",
            ),
            Task(
                id = "t5_7", title = "How much space?",
                chunks = listOf("`df` (disk free) shows storage; the dot means: the storage this folder is on.\n\n      `df -h .`"),
                command = "df -h .", chips = listOf("df", "-h", "."), keys = listOf("-", "."),
                prep = at,
                check = { a, _ -> a.ran("df") && (a.outHas("Size") || a.outHas("Avail")) },
                hint1 = "`df`, `-h`, and a dot, with spaces between.", hint2 = "`df -h .`",
                solution = "df -h .", solutionWhy = "`df -h .` shows the size and free space of the storage your app's room is on.",
                fact = "Your app's room is on the `/data` part of the storage, shared by all apps; the system itself is on parts nobody may change.",
                how = "df printed its table",
            ),
            Task(
                id = "t5_8", title = "The first wall",
                card = "On a computer, `/dev` holds the **devices**: the disk, the sound, the keyboard, each one a file. Let's look at the phone's.",
                chunks = listOf("**An error is the right result here.** Try it:\n\n      `ls /dev`"),
                command = "ls /dev", chips = listOf("ls", "/dev"), keys = listOf("/"),
                prep = at,
                check = { a, _ -> a.ran("ls") && "/dev" in a.words },
                hint1 = "`ls` and `/dev`, with the slash in front.", hint2 = "`ls /dev`",
                solution = "ls /dev", solutionWhy = "`ls /dev` asks for the list of devices. An app is not allowed to see it.",
                fact = "Permission denied: your first wall. On a phone every app sits in its own sandbox, and the list of hardware is outside it. You will meet more walls, and in Level 10 you find out who builds them.",
                how = "ls /dev ran (refused on a phone)",
            ),
            Task(
                id = "t5_9", title = "Digital dice",
                card = "Some devices an app may use by name. `/dev/urandom` hands out random bytes, forever. `head -c 12` takes twelve of them, and `base64` turns them into letters you can read.",
                chunks = listOf("Roll the dice:\n\n      `head -c 12 /dev/urandom | base64`"),
                command = "head -c 12 /dev/urandom | base64",
                parts = listOf("head -c 12" to "the first 12 bytes", "/dev/urandom" to "of endless randomness", "|" to "handed on", "base64" to "as readable letters"),
                chips = listOf("head", "-c", "12", "/dev/urandom", "|", "base64"), keys = listOf("-", "/", "|"),
                prep = at,
                check = { a, _ -> a.ran("base64") && Regex("""^[A-Za-z0-9+/]{16}$""").matches(a.output.trim()) },
                hint1 = "`head -c 12 /dev/urandom`, then a pipe, then `base64`.", hint2 = "`head -c 12 /dev/urandom | base64`",
                solution = "head -c 12 /dev/urandom | base64", solutionWhy = "Twelve random bytes, written as sixteen letters and digits.",
                fact = "Press ↑ and Enter: a new result every time. Passwords and encryption keys start like this.",
                how = "base64 printed sixteen random characters",
            ),
            Task(
                id = "t5_10", title = "A result and an error",
                chunks = listOf("Ask `ls` for two files. One exists, one does not:\n\n      `ls timeline.txt nothing.txt`"),
                command = "ls timeline.txt nothing.txt", chips = listOf("ls", "timeline.txt", "nothing.txt"),
                prep = at,
                check = { a, _ -> a.ran("ls") && a.lines().any { it == "timeline.txt" } && a.outHas("nothing.txt") },
                hint1 = "`ls` and both names.", hint2 = "`ls timeline.txt nothing.txt`",
                solution = "ls timeline.txt nothing.txt", solutionWhy = "One line is the result (timeline.txt), one is an error (nothing.txt is not there).",
                fact = "They look alike on the screen, but a command sends them out on two separate channels: the **result** and the **errors**.",
                how = "the output has the result and the error",
            ),
            Task(
                id = "t5_11", title = "Make the result disappear",
                card = "`/dev/null` is the bin: whatever goes in, disappears. `>` sends the result there; the errors still come to the screen.",
                chunks = listOf("Tap **↑** and add the end:\n\n      `ls timeline.txt nothing.txt > /dev/null`"),
                command = "ls timeline.txt nothing.txt > /dev/null",
                chips = listOf("ls", "timeline.txt", "nothing.txt", ">", "/dev/null"), keys = listOf(">", "/"),
                prep = at,
                check = { a, _ -> a.ran("ls") && a.outHas("nothing.txt") && a.lines().none { it == "timeline.txt" } },
                hint1 = "The line from before, then ` > /dev/null`.", hint2 = "`ls timeline.txt nothing.txt > /dev/null`",
                solution = "ls timeline.txt nothing.txt > /dev/null", solutionWhy = "`>` sent the result into the bin. Only the error is left.",
                fact = "This is how you tell them apart: the error survived, because `>` only catches the result.",
                how = "only the error is left on the screen",
            ),
            Task(
                id = "t5_12", title = "Make the error disappear",
                card = "`2>` catches the errors instead (channel number 2).",
                chunks = listOf("↑ again, and change `>` to `2>`:\n\n      `ls timeline.txt nothing.txt 2> /dev/null`"),
                command = "ls timeline.txt nothing.txt 2> /dev/null",
                chips = listOf("ls", "timeline.txt", "nothing.txt", "2>", "/dev/null"), keys = listOf(">", "/"),
                prep = at,
                check = { a, _ -> a.ran("ls") && a.lines() == listOf("timeline.txt") },
                hint1 = "Like before, but `2>` instead of `>`.", hint2 = "`ls timeline.txt nothing.txt 2> /dev/null`",
                solution = "ls timeline.txt nothing.txt 2> /dev/null", solutionWhy = "`2>` sent the error into the bin. Only the result is left.",
                fact = "Scripts use `2> /dev/null` to keep expected errors quiet. Use it with care: an error you do not see can still matter.",
                how = "only the result is left",
            ),
        ),
        outro = listOf(
            "Linux kernel, Android version, model, cores, memory, storage: you read them yourself, no app needed.",
            "And you hit the first wall: `/dev` is closed to apps. Every app on your phone lives behind such walls. Next level: who is in there with you.",
        ),
        explore = listOf(
            "Settings > About phone: find the Android version and the model you just read with getprop.",
            "Settings > About phone > Android version: the kernel version is there too.",
        ),
    )
}
